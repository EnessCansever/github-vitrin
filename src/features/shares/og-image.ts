import "server-only";

import {z} from "zod";
import {loadPublicShare} from "./read";
import {readShare} from "../../lib/db/share-reports";
import {summaryCardContent} from "../cards/content";
import {cachedCard} from "../cards/cache";
import {limitRequest,requestFailure} from "../../lib/security/requests";

export const previewHeaders={
  "Cache-Control":"private, no-store, max-age=0",
  "CDN-Cache-Control":"no-store",
  "Vercel-CDN-Cache-Control":"no-store",
  "Referrer-Policy":"no-referrer",
  "X-Robots-Tag":"noindex, nofollow, noarchive",
  "X-Content-Type-Options":"nosniff",
};

function failure(code:string,status:number,retryAt?:string): Response {
  const headers=new Headers(previewHeaders);
  if(retryAt)headers.set("Retry-After",String(Math.max(0,Math.ceil((Date.parse(retryAt)-Date.now())/1000))));
  return Response.json({code},{status,headers});
}

export async function shareImage(id:unknown,language:unknown):Promise<Response> {
  const result=await loadPublicShare(id);
  if(result.status==="error")return failure(result.code,result.code==="missing"?404:result.code==="rateLimit"?429:503,result.retryAt);
  const locale=z.enum(["tr","en"]).safeParse(language);
  if(!locale.success)return failure("invalid",400);
  const content=summaryCardContent(result.share.summary,locale.data);
  if(!content)return failure("incomplete",422);
  try{await limitRequest("card");}catch(error){const errorType=requestFailure(error);return failure(errorType?.code??"unavailable",errorType?.code==="rateLimit"?429:503,errorType?.retryAt);}
  try{
    const png=await cachedCard("share", result.share.id, result.share.expiresAt, locale.data, "landscape", content);
    // Closing/expiry during rendering must discard the already generated bytes.
    if(!await readShare(result.share.id))return failure("missing",404);
    return new Response(png,{headers:{...previewHeaders,"Content-Type":"image/png"}});
  }catch{return failure("unavailable",503);}
}
